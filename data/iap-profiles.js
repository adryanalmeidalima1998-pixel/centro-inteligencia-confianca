// Regras de confiabilidade de amostra por minutos
export function getConfiabilidade(minutos) {
  const m = parseInt(minutos) || 0
  if (m >= 700) return { label: 'Alta',       cor: '#16a34a', nivel: 4 }
  if (m >= 450) return { label: 'Média',      cor: '#ca8a04', nivel: 3 }
  if (m >= 300) return { label: 'Baixa',      cor: '#ea580c', nivel: 2 }
  return          { label: 'Muito Baixa',  cor: '#dc2626', nivel: 1 }
}
