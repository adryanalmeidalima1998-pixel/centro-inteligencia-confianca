// Resolve o grupo de um jogador dado string de posicao (ex: "LW, CF")
export function resolveGrupo(posStr) {
  if (!posStr) return null
  const parts = posStr.split(',').map(p => p.trim())
  // Prioriza a primeira posição
  for (const p of parts) {
    if (POSICAO_GRUPO[p]) return POSICAO_GRUPO[p]
  }
  return null
}

